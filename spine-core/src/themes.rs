/// Allowed Simple Mode asset slots copied into `<media_dir>/custom/<slot>.<ext>`.
fn allowed_exts_for_slot(slot: &str) -> Option<&'static [&'static str]> {
    match slot {
        "wallpaper" | "tv-wallpaper" => Some(WALLPAPER_EXTS),
        "font" | "tv-font" => Some(FONT_FILE_EXTS),
        "music" | "tv-music" => Some(MUSIC_FILE_EXTS),
        _ => None,
    }
}

/// Copy a user-chosen wallpaper, font, or music file into `<media_dir>/custom/<slot>.<ext>`.
/// Returns `(relative_media_url_with_stamp, original_file_name)`.
pub fn install_custom_asset(media_dir: &Path, slot: &str, src: &Path) -> Result<(String, String), String> {
    let allowed = allowed_exts_for_slot(slot).ok_or("Unknown asset slot.")?;
    let ext = file_ext(src);
    if !allowed.contains(&ext.as_str()) {
        return Err(format!("Unsupported file type (.{ext})."));
    }
    let custom_dir = media_dir.join("custom");
    fs::create_dir_all(&custom_dir).map_err(|e| format!("Couldn't create custom folder: {e}"))?;
    clear_custom_asset(media_dir, slot);
    let fname = format!("{slot}.{ext}");
    let dest = custom_dir.join(&fname);
    fs::copy(src, &dest).map_err(|e| format!("Couldn't copy file: {e}"))?;
    let v = fs::metadata(&dest)
        .and_then(|m| m.modified())
        .ok()
        .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let orig = src
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or(&fname)
        .to_string();
    Ok((format!("custom/{fname}?v={v}"), orig))
}

/// Remove any file stored for a Simple Mode asset slot.
pub fn clear_custom_asset(media_dir: &Path, slot: &str) {
    if allowed_exts_for_slot(slot).is_none() {
        return;
    }
    let custom_dir = media_dir.join("custom");
    let Ok(rd) = fs::read_dir(&custom_dir) else {
        return;
    };
    let prefix = format!("{slot}.");
    for ent in rd.flatten() {
        if let Some(name) = ent.file_name().to_str() {
            if name.starts_with(&prefix) {
                let _ = fs::remove_file(ent.path());
            }
        }
    }
}

#[derive(Debug, Clone, Deserialize)]
pub struct CustomThemeSpec {
    pub name: String,
    #[serde(default)]
    pub author: String,
    #[serde(default)]
    pub base: String,
    #[serde(default)]
    pub colors: BTreeMap<String, String>,
    #[serde(default)]
    pub style: Option<ThemeStyle>,
    #[serde(default, rename = "wallpaperRel")]
    pub wallpaper_rel: Option<String>,
    #[serde(default, rename = "fontRel")]
    pub font_rel: Option<String>,
    #[serde(default, rename = "fontFamily")]
    pub font_family: Option<String>,
    #[serde(default, rename = "musicRel")]
    pub music_rel: Option<String>,
}

fn resolve_media_file(media_dir: &Path, rel: &str) -> Option<PathBuf> {
    let clean = rel.split('?').next().unwrap_or(rel);
    let safe = safe_rel(clean)?;
    let full = media_dir.join(safe);
    full.is_file().then_some(full)
}

/// Save a Simple Mode customization as a real, shareable Theme Pack under `<themes_dir>/<id>/`.
pub fn save_custom_theme(
    themes_dir: &Path,
    media_dir: &Path,
    spec: &CustomThemeSpec,
) -> Result<ThemePack, String> {
    let trimmed_name = spec.name.trim();
    if trimmed_name.is_empty() || trimmed_name.chars().count() > 48 {
        return Err("Theme name must be 1 to 48 characters.".into());
    }
    fs::create_dir_all(themes_dir).map_err(|e| format!("Couldn't create themes folder: {e}"))?;

    let base_id = sanitize_id(trimmed_name);
    let mut id = base_id.clone();
    let mut n = 2u32;
    while themes_dir.join(&id).exists() {
        id = format!("{base_id}-{n}");
        n += 1;
    }
    let dir = themes_dir.join(&id);
    fs::create_dir_all(&dir).map_err(|e| format!("Couldn't create theme folder: {e}"))?;

    let mut colors = BTreeMap::new();
    for (k, v) in &spec.colors {
        let key = k.trim().trim_start_matches("--").to_ascii_lowercase();
        if !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_') {
            if let Some(val) = clean_css_val(v) {
                colors.insert(key, val);
            }
        }
    }

    // Copy optional wallpaper into wallpapers/default.<ext>
    if let Some(ref wp) = spec.wallpaper_rel {
        if let Some(src) = resolve_media_file(media_dir, wp) {
            let ext = file_ext(&src);
            if WALLPAPER_EXTS.contains(&ext.as_str()) {
                let wp_dir = dir.join("wallpapers");
                fs::create_dir_all(&wp_dir).map_err(|e| e.to_string())?;
                fs::copy(&src, wp_dir.join(format!("default.{ext}"))).map_err(|e| e.to_string())?;
            }
        }
    }

    // Copy optional uploaded font into fonts/<family>.<ext> and point --display / --body to it
    if let Some(ref fp) = spec.font_rel {
        if let Some(src) = resolve_media_file(media_dir, fp) {
            let ext = file_ext(&src);
            if FONT_FILE_EXTS.contains(&ext.as_str()) {
                let f_dir = dir.join("fonts");
                fs::create_dir_all(&f_dir).map_err(|e| e.to_string())?;
                let stem_raw = spec
                    .font_family
                    .as_deref()
                    .filter(|s| !s.trim().is_empty())
                    .unwrap_or("CustomFont");
                let stem: String = stem_raw
                    .chars()
                    .filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_' || *c == ' ')
                    .collect::<String>()
                    .trim()
                    .to_string();
                let fam = if stem.is_empty() { "CustomFont".to_string() } else { stem };
                fs::copy(&src, f_dir.join(format!("{fam}.{ext}"))).map_err(|e| e.to_string())?;
                let stack = format!("'{fam}', system-ui, sans-serif");
                colors.insert("display".into(), stack.clone());
                colors.insert("body".into(), stack);
            }
        }
    }

    // Copy optional music file into music/default.<ext>
    if let Some(ref mp) = spec.music_rel {
        if let Some(src) = resolve_media_file(media_dir, mp) {
            let ext = file_ext(&src);
            if MUSIC_FILE_EXTS.contains(&ext.as_str()) {
                let m_dir = dir.join("music");
                fs::create_dir_all(&m_dir).map_err(|e| e.to_string())?;
                fs::copy(&src, m_dir.join(format!("default.{ext}"))).map_err(|e| e.to_string())?;
            }
        }
    }

    let base = match spec.base.trim().to_ascii_lowercase().as_str() {
        "cream" => "cream",
        "crt" => "crt",
        "glass-light" => "glass-light",
        "glass-dark" => "glass-dark",
        "tv" => "tv",
        _ => "midnight",
    }
    .to_string();

    let manifest = ThemeManifest {
        name: trimmed_name.to_string(),
        author: if spec.author.trim().is_empty() {
            "Custom".into()
        } else {
            spec.author.trim().to_string()
        },
        version: "1.0.0".into(),
        description: "Created in Spine's Customize look editor.".into(),
        base,
        preview: None,
        icon_mode: None,
        colors,
        style: spec.style.clone(),
        options: vec![],
    };

    let json = serde_json::to_string_pretty(&manifest).map_err(|e| e.to_string())?;
    fs::write(dir.join("theme.json"), json).map_err(|e| e.to_string())?;

    load_theme(&dir).ok_or_else(|| "Failed to load saved custom theme.".into())
}

