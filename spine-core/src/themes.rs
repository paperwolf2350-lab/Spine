    #[test]
    fn custom_assets_and_save_custom_theme() {
        let root = temp_dir("custom-save");
        let media = root.join("media");
        let themes = root.join("themes");
        let src_dir = root.join("src");
        fs::create_dir_all(&src_dir).unwrap();
        let wp = src_dir.join("bg.jpg");
        let font = src_dir.join("MyFont.ttf");
        let song = src_dir.join("chill.mp3");
        fs::write(&wp, b"fakejpg").unwrap();
        fs::write(&font, b"fakefont").unwrap();
        fs::write(&song, b"fakemp3").unwrap();

        let (wp_rel, wp_name) = install_custom_asset(&media, "wallpaper", &wp).unwrap();
        let (font_rel, _) = install_custom_asset(&media, "font", &font).unwrap();
        let (music_rel, _) = install_custom_asset(&media, "music", &song).unwrap();
        assert_eq!(wp_name, "bg.jpg");
        assert!(wp_rel.starts_with("custom/wallpaper.jpg?v="));

        // Bad extension rejected
        let bad = src_dir.join("nope.exe");
        fs::write(&bad, b"mz").unwrap();
        assert!(install_custom_asset(&media, "wallpaper", &bad).is_err());

        let mut colors = BTreeMap::new();
        colors.insert("bg".into(), "#10141C".into());
        colors.insert("accent".into(), "#FF6B35".into());
        let spec = CustomThemeSpec {
            name: "Cozy Sunset".into(),
            author: "Alex".into(),
            base: "midnight".into(),
            colors,
            style: Some(ThemeStyle {
                radius: Some("soft".into()),
                glass: Some(true),
                wallpaper_dim: Some(0.45),
                wallpaper_blur: Some(4.0),
                cover_wall: Some(false),
                sound_style: Some("cube".into()),
            }),
            wallpaper_rel: Some(wp_rel),
            font_rel: Some(font_rel),
            font_family: Some("MyFont".into()),
            music_rel: Some(music_rel),
        };

        let pack = save_custom_theme(&themes, &media, &spec).unwrap();
        assert_eq!(pack.id, "cozy-sunset");
        assert!(pack.has_visual && pack.has_music);
        assert!(pack.wallpapers.contains_key("default"));
        assert!(pack.music.contains_key("default"));
        assert_eq!(pack.fonts.len(), 1);
        assert_eq!(pack.fonts[0].family, "MyFont");
        assert_eq!(pack.style.as_ref().and_then(|s| s.sound_style.as_deref()), Some("cube"));

        // Saving again with same name creates unique suffix without overwriting
        let pack2 = save_custom_theme(&themes, &media, &spec).unwrap();
        assert_eq!(pack2.id, "cozy-sunset-2");

        // Clearing asset removes file
        clear_custom_asset(&media, "wallpaper");
        assert!(!media.join("custom/wallpaper.jpg").exists());

        let _ = fs::remove_dir_all(&root);
    }

