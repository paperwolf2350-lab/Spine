//! Theme packs: scan `<data_dir>/themes/`, load manifests (`theme.json`),
//! discover safe assets (CSS, fonts, wallpapers, console icons, music, UI
//! sound effects, and custom mascot packs), import/export `.zip` packs, and
//! generate a starter theme for creators.
//!
//! Security: themes are strictly declarative (CSS + JSON + media assets).
//! Executable files and scripts (`.js`, `.html`, etc.) are never imported
//! or exposed.

use crate::systems;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::fs;
use std::io::{self, Read, Write};
use std::path::{Component, Path, PathBuf};
use std::time::UNIX_EPOCH;

const MAX_ZIP_FILES: usize = 500;
const MAX_ZIP_BYTES: u64 = 150 * 1024 * 1024; // 150 MB

const RESERVED_IDS: &[&str] = &[
    "cream",
    "midnight",
    "crt",
    "glass-light",
    "glass-dark",
    "tv",
    "default",
    "none",
    "off",
    "theme",
    "mono",
    "systematic",
    "lines",
    "paige",
];

pub const WALLPAPER_EXTS: &[&str] = &["png", "jpg", "jpeg", "webp", "gif"];
pub const FONT_FILE_EXTS: &[&str] = &["woff2", "woff", "ttf", "otf"];
pub const MUSIC_FILE_EXTS: &[&str] = &["mp3", "ogg", "wav", "m4a"];

const IMG_EXTS: &[&str] = &["png", "jpg", "jpeg", "webp", "gif", "svg"];
const FONT_EXTS: &[&str] = FONT_FILE_EXTS;
const AUDIO_EXTS: &[&str] = MUSIC_FILE_EXTS;

/// Allowed file extensions inside a theme pack (for zip import and HTTP serving).
pub fn is_safe_asset_ext(ext: &str) -> bool {
    matches!(
        ext.to_ascii_lowercase().as_str(),
        "json"
            | "css"
            | "txt"
            | "md"
            | "png"
            | "jpg"
            | "jpeg"
            | "webp"
            | "gif"
            | "svg"
            | "woff2"
            | "woff"
            | "ttf"
            | "otf"
            | "mp3"
            | "ogg"
            | "wav"
            | "m4a"
    )
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct ThemeChoice {
    pub value: String,
    pub label: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ThemeOption {
    pub id: String,
    pub label: String,
    #[serde(default)]
    pub note: String,
    /// `"toggle"` (on/off) or `"choice"` (list of choices).
    #[serde(default = "default_opt_type", rename = "type")]
    pub kind: String,
    #[serde(default)]
    pub choices: Vec<ThemeChoice>,
    #[serde(default)]
    pub default: serde_json::Value,
}

fn default_opt_type() -> String {
    "toggle".into()
}

